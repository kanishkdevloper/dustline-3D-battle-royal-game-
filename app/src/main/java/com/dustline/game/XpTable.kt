    fun levelFromXp(x: Long): Int {
        val v = maxOf(0L, x)
        var lo = 0; var hi = TABLE.size - 1
        while (lo < hi) { val m = (lo + hi + 1) shr 1; if (TABLE[m] <= v) lo = m else hi = m - 1 }
        return lo + 1
    }

    fun progress(x: Long): Float {
        val l = levelFromXp(x)
        if (l >= TABLE.size) return 1f
        val a = TABLE[l - 1]; val b = TABLE[l]
        return ((x - a).toFloat() / (b - a).toFloat()).coerceIn(0f, 1f)
    }
